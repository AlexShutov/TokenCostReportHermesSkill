#!/usr/bin/env python3
"""Определения атрибуций инкрементов — одна общая для обоих путей (append-база и ядро плана).

Атрибуции:
  delta      — настоящий интервал между двумя наблюдениями
  first_seen — строка впервые увиденная (окно first_seen..last_seen)
  backfill   — строки, существовавшие до создания базы (атрибутированы точкой last_seen)
  gap        — интервал наблюдения длиннее порога: крон-задача не сработала, машина спала,
               агент завис. Токены за такой интервал реальны, но разложить их по времени
              нельзя — весь прирост ушёл бы в день window_end и исказил «по дням».
               Такие интервалы выбрасываются из сумм, но остаются в базе (append-only).
  anomaly    — строка уменьшилась или исчезла

EXCLUDED_ATTRIBUTION — атрибуции, которые не входят ни в суточное окно, ни в «по дням»,
ни в кредиты плана. Определяется ОДИН раз, чтобы база и ядро плана не разошлись.
"""
import os

EXCLUDED_ATTRIBUTION = ("anomaly", "gap")

# Порог выбрасываемого интервала: по умолчанию 20 минут — это два тика крона по 10 минут.
# Зависание получасовой давности попадает под порог и не искажает «по дням».
# Меняется переменной TOKEN_COST_MAX_WINDOW (секунды).
MAX_WINDOW_SECONDS = int(os.environ.get("TOKEN_COST_MAX_WINDOW", 1200))


def excluded_sql():
    """Одна строка WHERE для всех сумм — иначе путь базы и путь плана разошлись бы."""
    return "attribution NOT IN (" + ", ".join("?" for _ in EXCLUDED_ATTRIBUTION) + ")"
